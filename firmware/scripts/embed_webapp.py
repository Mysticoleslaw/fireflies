# Pre-build step: gzips the web app into src/generated/webapp_files.h so every firmware
# image carries its own app (no separate filesystem upload, which used to wipe settings),
# and writes src/generated/build_info.h with a fingerprint of the source code so bugs can
# report which build they run. Files are only rewritten when their content changes.
import gzip
import zlib
from pathlib import Path

Import("env")  # noqa: F821 (provided by PlatformIO)

project = Path(env.subst("$PROJECT_DIR"))  # noqa: F821
webapp = project.parent / "webapp"
out = project / "src" / "generated"
FILES = [("index.html", "text/html"), ("app.js", "text/javascript"), ("bugs.js", "text/javascript")]
SOURCES = ["src/*.cpp", "src/*.h", "lib/core/*", "platformio.ini"]


def write_if_changed(path: Path, text: str) -> None:
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def c_array(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"const uint8_t {name}[] PROGMEM = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def embed_webapp() -> None:
    parts = ["// Generated by scripts/embed_webapp.py from ../webapp. Do not edit.", "#pragma once",
             "#include <Arduino.h>", ""]
    table = []
    for i, (name, mime) in enumerate(FILES):
        data = gzip.compress((webapp / name).read_bytes(), compresslevel=9, mtime=0)
        parts.append(c_array(f"kWebFile{i}", data))
        table.append(f'  {{"/{name}", "{mime}", kWebFile{i}, sizeof kWebFile{i}}},')
    parts += ["struct WebFile {", "  const char* path;", "  const char* mime;", "  const uint8_t* gz;",
              "  size_t size;", "};", "", "const WebFile kWebFiles[] = {", *table, "};", ""]
    write_if_changed(out / "webapp_files.h", "\n".join(parts))


def build_fingerprint() -> int:
    crc = 0
    paths = sorted({p for pattern in SOURCES for p in project.glob(pattern)} | {webapp / n for n, _ in FILES})
    for path in paths:
        if path.is_file() and "generated" not in path.parts:
            crc = zlib.crc32(path.name.encode() + path.read_bytes(), crc)
    return crc


out.mkdir(parents=True, exist_ok=True)
embed_webapp()
write_if_changed(out / "build_info.h",
                 "// Generated by scripts/embed_webapp.py. Do not edit.\n#pragma once\n"
                 f"#define FF_BUILD_ID 0x{build_fingerprint():08x}UL  // fingerprint of the source code\n")
